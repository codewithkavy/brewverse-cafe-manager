val releaseProperties = Properties()
val releasePropertiesFile = rootProject.file("key.properties")
if (releasePropertiesFile.exists()) releasePropertiesFile.inputStream().use { releaseProperties.load(it) }
fun releaseValue(environment: String, property: String): String? =
    System.getenv(environment)?.takeIf { it.isNotBlank() }
        ?: releaseProperties.getProperty(property)?.takeIf { it.isNotBlank() }
val releaseStore = releaseValue("BREWVERSE_RELEASE_STORE_FILE", "storeFile")
val releaseAlias = releaseValue("BREWVERSE_RELEASE_KEY_ALIAS", "keyAlias")
val releaseStorePassword = releaseValue("BREWVERSE_RELEASE_STORE_PASSWORD", "storePassword")
val releaseKeyPassword = releaseValue("BREWVERSE_RELEASE_KEY_PASSWORD", "keyPassword")
val hasReleaseSigning = listOf(releaseStore, releaseAlias, releaseStorePassword, releaseKeyPassword).all { it != null }
if (gradle.startParameter.taskNames.any { it.contains("release", ignoreCase = true) } && !hasReleaseSigning) {
    throw GradleException("Release signing is required. Use scripts/build-release.ps1; debug signing is never used for release.")
}

